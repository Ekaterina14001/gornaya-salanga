HIGHLIGHT_FILL = "FFF59D"
FONT_NAME = "Times New Roman"


def shade_paragraph(paragraph, fill: str = HIGHLIGHT_FILL):
    """Word export: без подсветки (чистый текст для договора)."""
    del paragraph, fill


def shade_table_row(row, fill: str = HIGHLIGHT_FILL):
    del row, fill


def fmt_run(run, *, bold=False, size_pt=11):
    run.font.name = FONT_NAME
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT_NAME)
    run.font.size = Pt(size_pt)
    run.font.bold = bold
    run.font.color.rgb = RGBColor(0, 0, 0)


def add_para(
    doc: Document,
    text: str,
    *,
    align=WD_ALIGN_PARAGRAPH.JUSTIFY,
    bold=False,
    size_pt=11,
    space_before=0,
    space_after=6,
    highlight=False,
    left_indent_cm=0,
):
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = 1.15
    if left_indent_cm:
        pf.left_indent = Cm(left_indent_cm)
    run = p.add_run(text)
    fmt_run(run, bold=bold, size_pt=size_pt)
    if highlight:
        shade_paragraph(p)
    return p


