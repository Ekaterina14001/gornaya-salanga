        table.style = "Table Grid"
        for i, (a, b) in enumerate(rows):
            row = table.rows[i]
            row.cells[0].text = a.replace("<b>", "").replace("</b>", "")
            row.cells[1].text = b.replace("<b>", "").replace("</b>", "")
            for cell in row.cells:
                for par in cell.paragraphs:
                    for run in par.runs:
                        fmt_run(run, bold=(i == 0), size_pt=10)
            if i in highlight_rows:
                shade_table_row(row)
        self.doc.add_paragraph()

